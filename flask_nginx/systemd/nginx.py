def appname_func(params: dict[str, Any]) -> str:
    app = str(params["application_dir"])
    return str(split(app)[-1])


def fix_path(s: str) -> str:
    return s.removeprefix("/")


def nginx(  # noqa: C901, PLR0915, PLR0912
    application_dir: Path,
    server_name: str,
    args: list[str] | None = None,
    *,
    template_name: str | None = None,
    help_args: dict[str, str] | None = None,
    check: bool = True,
    output: str | TextIO | None = None,
    extra_params: dict[str, Any] | None = None,
    checks: list[tuple[str, CHECKTYPE]] | None = None,
    ignore_unknowns: bool = False,
    default_values: list[tuple[str, CONVERTER]] | None = None,
    convert: dict[str, Callable[[Any], Any]] | None = None,
    asgi: bool = False,
    exclusive: bool = False,
) -> str:
    """Generate an nginx configuration for application."""
    from jinja2 import UndefinedError

    from ..config import get_config

    if args is None:
        args = []

    if application_dir is None:
        msg = "no application directory"
        raise click.BadParameter(msg)

    if help_args is None:
        help_args = NGINX_ARGS

    convert = {"root": topath} if convert is None else {"root": topath, **convert}

    application_dir = topath(application_dir)
    template = get_template(template_name or "nginx.conf", application_dir)

    known = get_known(help_args) | {"staticdirs", "toplevel", "favicon", "error_pages"}
    # directory to match with / for say /favicon.ico
    root_location_match = None
    params: dict[str, Any] = {}
    try:
        # arguments from .flaskenv
        params = {k: v for k, v in footprint_config(application_dir).items() if k in known}
        params.update(fix_params(args, convert))
        if extra_params:
            params.update(extra_params)

        prefix = params.get("prefix", "")
        if "root" in params:
            root = str(topath(application_dir / str(params["root"])))
            params["root"] = root
            rp = params.get("root_prefix")
            staticdirs = [StaticFolder(rp if rp is not None else prefix, root, rewrite=False)]
        else:
            staticdirs = []
        # if the params have an app value use that as the entrypoint
        entrypoint = params.get("app")
        if entrypoint is None:
            entrypoint = get_app_entrypoint(application_dir, asgi=asgi)
        routes = []
        if entrypoint != "@none":
            app = find_application(entrypoint, str(application_dir))
            staticdirs.extend(
                get_static_folders_for_app(
                    app,
                    prefix=prefix,
                ),
            )
            if exclusive:
                routes = get_route_prefixes(app)  # just to check it works
                routes = [fix_path(r) for r in routes if r and r != "/"]
                if prefix:
                    routes = [f"{prefix[1:]}/{r}" for r in routes]
                click.secho(
                    f"Warning: exclusive routes: ^/({'|'.join(routes)})",
                    err=True,
                    fg="yellow",
                    bold=True,
                )

        error_pages = list(has_error_page(staticdirs, error_pages=[401, 403, 404, 500]))
        params["error_pages"] = error_pages
        params["staticdirs"] = staticdirs
        for s in staticdirs:
            if not s.url:  # top level?
                root_location_match = url_match(s.folder)
        # need a root directory for server
        if "root" not in params and not staticdirs:
            params["root"] = topath(application_dir)
        # add any defaults
        defaults: list[tuple[str, CONVERTER]] = [
            ("application_dir", lambda _: application_dir),
            ("appname", appname_func),
            ("root", lambda _: staticdirs[0].folder),
            ("server_name", lambda _: server_name),
        ]

        if default_values:
            defaults.extend(default_values)

        for key, default_func in defaults:
            if key not in params:
                v = default_func(params)
                if v is not None:
                    params[key] = v

        def isint(s: str | int) -> bool:
            return isinstance(s, int) or s.isdigit()

        if "host" in params:
            h = params["host"]
            if isint(h):
                params["host"] = "127.0.0.1"
                params["port"] = h
            elif ":" in h:
                s, h = h.rsplit(":", maxsplit=1)
                params["host"] = s
                params["port"] = h

        if "port" not in params:
            params["port"] = 8000

        if root_location_match is not None and "root_location_match" not in params:
            params["root_location_match"] = root_location_match
        if "toplevel" not in params and not root_location_match:
            d = find_toplevel(str(application_dir))
            if d:
                params["toplevel"] = str(topath(application_dir / d))

        if "toplevel" in params:
            params["toplevel"] = str(topath(params["toplevel"]))

        if check:
            msg = check_app_dir(str(application_dir))
            if msg:
                raise click.BadParameter(msg, param_hint="application_dir")

            if not ignore_unknowns:
                extra = set(params) - known
                if extra:
                    msg = f"unknown arguments {extra}"
                    raise click.BadParameter(
                        msg,
                        param_hint="params",
                    )
            failed: list[str] = []
            checks = (checks or []) + [
                to_check_func("root", isdir, '"{root}" is not a directory'),
                to_check_func("toplevel", isdir, '"{toplevel}" is not a directory'),
            ]
            for key, func in checks:
                if key in params:
                    v = params[key]
                    msg = func(key, v)
                    if msg is not None:
                        click.secho(
                            msg,
                            fg="yellow",
                            bold=True,
                            err=True,
                        )
                        failed.append(key)
                if failed:
                    raise click.Abort

        res = template.render(Config=get_config(), routes=routes, **params)
        to_output(res, output)
    except UndefinedError as e:
        undefined_error(e, template, params)
        raise click.Abort from e
    return res


