@config.command(name="nginx", help=NGINX_HELP)
@template_option
@config_options
@click.option(
    "--no-static",
    is_flag=True,
    help="Don't try to introspect static files. (Useful for non-flask websites)",
)
@asgi_option
@click.option(
    "-x",
    "--404",
    "exclude_urls",
    type=click.Path(exists=True, dir_okay=False, file_okay=True, path_type=Path),
    help="""list of urls to immediately return 404 for (one per line)""",
)
@click.option(
    "--exclusive",
    is_flag=True,
    help="""add a negative assertion to the known urls of the app.
 (Caution you can't add any new routes to the app after this)""",
)
@click.option(
    "-d",
    "--app-dir",
    "application_dir",
    type=click.Path(exists=True, dir_okay=True, file_okay=False, path_type=Path),
    help="""location of repo or current directory""",
)
@click.argument("server_name")
@click.argument("params", nargs=-1)
def nginx_cmd(  # noqa: PLR0917
    application_dir: Path | None,
    server_name: str,
    template: str | None,
    exclude_urls: Path | None,
    params: list[str],
    output: str | None,
    *,
    asgi: bool,
    no_check: bool,
    no_static: bool = False,
    exclusive: bool = False,
) -> None:
    """Generate nginx config file.

    PARAMS are key=value arguments for the template.
    """
    # pylint: disable=line-too-long
    # see https://www.digitalocean.com/community/tutorials/how-to-serve-flask-applications-with-gunicorn-and-nginx-on-ubuntu-20-04
    # place this in /etc/systemd/system/
    params = list(params)
    if no_static:
        params.append("app=@none")

    urls = []
    if exclude_urls:
        with exclude_urls.open("r", encoding="utf-8") as fp:
            for line in fp:
                line = line.strip()
                if line and line.startswith("/"):
                    urls.append(re.escape(line[1:]))
    nginx(
        application_dir or Path.cwd(),
        server_name,
        params,
        template_name=template,
        check=not no_check,
        output=output,
        asgi=asgi,
        extra_params={"exclude_urls": urls},
        exclusive=exclusive,
    )


@config.command(name="nginx-run-app", hidden=True)
@click.option("-p", "--port", default=5000, help="port to listen", show_default=True)
@click.option(
    "-x",
    "--no-start",
    "no_start_app",
    is_flag=True,
    help="don't start the website in background",
    show_default=True,
)
@click.option(
    "--entrypoint",
    help="web application entrypoint",
)
@asgi_option
@click.option("--browse", is_flag=True, help="open web application in browser")
@click.option(
    "-d",
    "--app-dir",
    "application_dir",
    type=click.Path(exists=True, dir_okay=True, file_okay=False),
    help="""location of repo or current directory""",
)
def nginx_run_app_cmd(
    application_dir: Path | None,
    port: int,
    entrypoint: str | None,
    *,
    asgi: bool,
    no_start_app: bool = False,
    browse: bool = False,
) -> None:
    """Run nginx as a non daemon process with web app in background."""
    import signal
    import uuid
    from tempfile import gettempdir

    from ..utils import browser, require_mod

    nginx_exe = which("nginx")

    if not no_start_app:
        if asgi:
            require_mod("uvicorn")
        else:
            require_mod("gunicorn")

    if application_dir is None:
        application_dir = Path.cwd()

    application_dir = topath(application_dir)
    tmplt = get_template("nginx-test.conf", application_dir)
    res = tmplt.render(  # pylint: disable=no-member
        application_dir=application_dir,
        port=port,
    )
    tmpfile = Path(gettempdir()) / f"nginx-{uuid.uuid4()}.conf"

    url = f"http://127.0.0.1:{port}"
    click.secho(f"listening on {url}", fg="green", bold=True)
    running: subprocess.Popen[bytes] | None = None
    brws: Thread | None = None
    try:
        with tmpfile.open("wt", encoding="utf-8") as fp:
            fp.write(res)

        if not no_start_app:
            app_entry = entrypoint or get_app_entrypoint(application_dir, asgi=asgi)
            running = run_app(
                application_dir,
                f"unix:{application_dir}/app.sock",
                app_entry,
                asgi=asgi,
            )
        else:
            click.secho(
                f"expecting app running in {application_dir} with app.sock as unix socket",
                fg="magenta",
                bold=True,
            )
        if browse:
            brws = browser(url=url)

        subprocess.check_call([nginx_exe, "-c", str(tmpfile)])

    finally:
        tmpfile.unlink(missing_ok=True)
        if running is not None:
            os.kill(running.pid, signal.SIGINT)
        if brws is not None:
            brws.join()


@config.command(name="nginx-run")
@click.option(
    "-p",
    "--port",
    default=5000,
    help="port for nginx to listen",
    show_default=True,
)
@click.option(
    "-u",
    "--upload-max",
    default="40M",
    help="""maximum file upload size possible.
    (if you try to upload more than this you will get mysterious permission denied errors to `/var/lib/nginx/body`)""",
    show_default=True,
)
@click.option(
    "--entrypoint",
    help="web application entrypoint. If not specified will try to find it in the application directory",
)
@asgi_option
@click.option("--browse", is_flag=True, help="open web application in browser")
@click.option(
    "-d",
    "--app-dir",
    "application_dir",
    type=click.Path(exists=True, dir_okay=True, file_okay=False, path_type=Path),
    help="""location of repo or current directory""",
)
@click.argument("nginxfile", type=click.File("rt", encoding="utf-8"), required=True)
@click.argument("server_args", nargs=-1)
def nginx_run_cmd(  # noqa: C901, PLR0915, PLR0917
    nginxfile: IO[str],
    application_dir: Path | None,
    entrypoint: str | None,
    port: int,
    upload_max: str,
    server_args: tuple[str, ...],
    *,
    browse: bool,
    asgi: bool,
) -> None:
    """Run nginx as a non daemon process using the specified nginxfile.

    This will test the generated nginx configuration file (especially the delivery of static files
    and 404 errors).
    """
    import signal
    from tempfile import NamedTemporaryFile

    from ..utils import browser, has_mod

    nginx_exe = which("nginx")
    if asgi:
        if not has_mod("uvicorn"):
            if not has_mod("gunicorn"):
                click.secho(
                    "neither `uvicorn` nor `gunicorn` is installed. Please install one of them.",
                    err=True,
                    fg="red",
                )
                raise click.Abort
            click.secho("maybe not an `--asgi` application?", err=True)
            raise click.Abort
    elif not has_mod("gunicorn"):
        if not has_mod("uvicorn"):
            click.secho(
                "neither `gunicorn` nor `uvicorn` is installed. Please install one of them.",
                err=True,
                fg="red",
            )
            raise click.Abort
        click.secho("maybe an `--asgi` application?", err=True)
        raise click.Abort

    def once(m: str) -> Callable[[re.Match[str]], str]:
        done = False

        def f(_r: re.Match[str]) -> str:
            nonlocal done
            if done:
                return ""
            done = True
            return m

        return f

    def get_server() -> tuple[str, str | None]:
        """Parse nginx.conf file for server and host."""
        access_re = re.compile("access_log [^;]+;")  # remove access log entries
        # see comment in nginx-app.conf about client_body_buffer_size and client_max_body_size
        max_body_re = re.compile("(client_max_body_size|client_body_buffer_size) [^;]+;")
        listen_re = re.compile("listen [^;]+;")  # replace listen {port}; with our port
        proxy_pass_re = re.compile(
            r"proxy_pass\s+http://([^\s]+)/?\s*;",
        )  # find where the proxy app.sock is..
        # search for say:
        #    upstream app {
        #        server unix:{{application_dir}}/app.sock fail_timeout=0;
        #    } # noqa: ERA001
        server_re = re.compile(r"server\s+([^{\s]+)/?.*;")

        server = nginxfile.read()
        # remove old access_log and replace listen commands
        server = access_re.sub("", server)
        server = max_body_re.sub("", server)
        server = listen_re.sub(once(f"listen {port};"), server)
        # find unix socket locations
        m = server_re.search(server) or proxy_pass_re.search(server)
        bind = None if not m else m.group(1)
        return server, bind

    template: Template = get_template("nginx-app.conf", application_dir)
    server, bind = get_server()
    if not bind or not bind.startswith("unix:"):
        click.secho("can't find unix: socket entrypoint in file", err=True, fg="red")
        raise click.Abort
    application_dir = application_dir or Path.cwd()
    entry = entrypoint or get_app_entrypoint(application_dir, asgi=asgi)
    nginx_conf = template.render(server=server, upload_max=upload_max)
    threads: list[threading.Thread] = []

    with NamedTemporaryFile("w") as fp:
        fp.write(nginx_conf)
        fp.flush()
        url = f"http://127.0.0.1:{port}"
        click.secho(f"listening on {url}", fg="green", bold=True)
        app = run_app(application_dir, bind, entry, asgi=asgi, args=server_args)

        if browse:
            threads.append(browser(url))
        try:
            subprocess.run([nginx_exe, "-c", fp.name], check=False)
        finally:
            os.kill(app.pid, signal.SIGINT)
            for thrd in threads:
                thrd.join(timeout=2.0)


@config.command(name="nginx-install")
@click.option(
    "--check-only",
    default=True,
    is_flag=True,
    help="check if nginx differs from existing config",
)
@click.argument(
    "nginxfile",
    type=click.Path(exists=True, dir_okay=False, file_okay=True),
)
def nginx_install_cmd(nginxfile: str, *, check_only: bool) -> None:
    """Install nginx config file."""
    # install frontend
    conf = nginx_install(nginxfile, check_only=check_only)
    if not check_only:
        if conf is None:
            raise click.Abort

        click.secho(f"{conf} installed!", fg="green", bold=True)


