def ensure_package(exe: str, python_executable: str | None = None) -> None:
    if not has_mod(exe, python_executable):
        click.secho(
            f"{exe} is not installed. Please install it with `pip install {exe}`",
            fg="red",
            bold=True,
            err=True,
        )
        raise click.Abort


def run_app(
    application_dir: Path,
    bind: str,
    entrypoint: str,
    *,
    asgi: bool,
    webserver: str,  # Literal["uvicorn", "hypercorn", "gunicorn"],
    args: tuple[str, ...] = (),
    python_executable: str | None = None,
) -> subprocess.Popen[bytes]:

    if python_executable is None:
        python_executable = sys.executable

    if asgi:
        if webserver == "uvicorn":
            if bind.startswith("unix:"):
                binds = [f"--uds={bind[len('unix:') :]}"]
            else:
                host, port = bind.split(":", maxsplit=1)
                binds = [f"--host={host}", f"--port={port}"]
            exe = "uvicorn"
            cmd = [
                python_executable,
                "-m",
                exe,
                "--proxy-headers",
                *binds,
                *args,
                entrypoint,
            ]
        elif webserver == "hypercorn":
            exe = "hypercorn"
            cmd = [
                python_executable,
                "-m",
                exe,
                "--bind",
                bind,
                "--access-logfile=-",
                "--error-logfile=-",
                *args,
                entrypoint,
            ]
        else:  # webserver == "gunicorn"
            exe = "gunicorn"
            cmd = [
                python_executable,
                "-m",
                exe,
                "--worker-class=asgi",
                "--access-logfile=-",
                "--error-logfile=-",
                "--bind",
                bind,
                *args,
                entrypoint,
            ]

    else:
        exe = "gunicorn"
        cmd = [
            python_executable,
            "-m",
            exe,
            "--access-logfile=-",
            "--error-logfile=-",
            "--bind",
            bind,
            *args,
            entrypoint,
        ]

    ensure_package(exe, python_executable)
    click.secho(
        f"starting {exe} in {topath(application_dir)}",
        fg="green",
        bold=True,
    )

    click.secho(" ".join(cmd), fg="yellow")
    return subprocess.Popen(cmd, cwd=application_dir, env=os.environ)


def patch_nginx_conf(oldfile: Path, newfile: Path) -> Path:  # noqa: C901, PLR0912
    """Ensure we don't overwrite any existing nginx configuration that has been patched by certbot or other tools."""
    newlines: list[str] = []
    active: bool = False
    with newfile.open("rt", encoding="utf-8") as fp:
        for line in fp:
            if line.lstrip().startswith("# >>> generated by footprint"):
                active = True
            elif line.lstrip().startswith("# <<< generated by footprint"):
                break
            elif active:
                newlines.append(line)
    if not newlines:
        msg = f"no '# >>> generated by footprint' lines found in {newfile.name}!"
        click.secho(msg, fg="red", err=True)
        raise click.Abort
    stem = f"{newfile.stem}-patched{newfile.suffix}"
    if os.access(newfile.parent, os.W_OK):  # noqa: SIM108
        nnewfile = newfile.parent / stem
    else:
        nnewfile = Path(tempfile.gettempdir()) / stem
    certbot = "# managed by Certbot" in oldfile.read_text(encoding="utf-8")
    with nnewfile.open("wt", encoding="utf-8") as fp:
        patched = False
        active = False

        with oldfile.open("rt", encoding="utf-8") as olfp:
            for line in olfp:
                if line.lstrip().startswith("# >>> generated by footprint"):
                    active = True
                    fp.write(line)
                    for newline in newlines:
                        # skip any listen lines if certbot has already added them
                        if certbot and newline.lstrip().startswith("listen"):
                            continue
                        fp.write(newline)
                    patched = True
                elif line.lstrip().startswith("# <<< generated by footprint"):
                    active = False
                    fp.write(line)
                elif not active:
                    fp.write(line)
    if active:
        nnewfile.unlink(missing_ok=True)
        msg = f"no '# <<< generated by footprint' line found in {oldfile.name}!"
        click.secho(msg, fg="red", err=True)
        raise click.Abort
    if not patched:
        nnewfile.unlink(missing_ok=True)
        if certbot:
            msg = "found certbot managed nginx file but no footprint generated lines to patch!"
            click.secho(msg, fg="red", err=True)
            raise click.Abort
        return newfile
    click.secho(
        f"patched {oldfile.name} to {nnewfile.name}",
        fg="yellow",
        bold=True,
        err=True,
    )
    return nnewfile


def nginx_install(nginxconf: str, *, check_only: bool = False, patch_file: bool = True) -> str | None:  # noqa: C901, PLR0915, PLR0912
    import filecmp

    from ..config import get_config

    nginxfile = Path(nginxconf)

    config = get_config()

    conf = nginxfile.name
    # Ubuntu, RHEL8
    for td in config.nginx_dirs:
        targetd = Path(td)
        if targetd.is_dir():
            break
    else:
        msg = "can't find nginx configuration directory."
        click.secho(msg, fg="red", err=True)
        raise click.Abort
    sudo = which("sudo")
    systemctl = which("systemctl")

    def sudocmd(*args: Any, check: bool = True) -> subprocess.CompletedProcess[bytes]:  # noqa: ANN401
        return subprocess.run([sudo] + [str(a) for a in args], check=check)

    def runcmd(*args: Any, check: bool = True) -> subprocess.CompletedProcess[bytes]:  # noqa: ANN401
        return subprocess.run([str(a) for a in args], check=check)

    def systemctlcmd(*args: Any, check: bool = True) -> int:  # noqa: ANN401
        return subprocess.run(
            [sudo, systemctl] + [str(a) for a in args],
            check=check,
        ).returncode

    conffile = targetd / conf

    exists = conffile.is_file()
    issame = exists and filecmp.cmp(conffile, nginxfile)
    if check_only:
        if exists:
            if issame:
                click.secho(
                    f"nginx file {conf} {'unchanged' if issame else 'changed'}",
                    fg="green" if issame else "yellow",
                )
        else:
            click.secho(f"installed nginx file {conf} does not exist", fg="yellow")
        return None

    if not issame:
        bak = None
        if exists and patch_file:
            # file might have been patched by certbot or other tools so we need to patch it
            nnginxfile = patch_nginx_conf(conffile, nginxfile)
            if os.access(nginxfile.parent, os.W_OK):
                bak = nginxfile.parent / f"{conffile.name}.bak"
            else:
                bak = Path(tempfile.gettempdir()) / f"{conffile.name}.bak"
            runcmd("cp", conffile, bak)
            if filecmp.cmp(conffile, nnginxfile):
                click.secho(f"nginx file {conf} unchanged", fg="green")
                if bak is not None:
                    bak.unlink(missing_ok=True)
                if nnginxfile != nginxfile:
                    nnginxfile.unlink(missing_ok=True)
                return conf
            click.secho(f"warning: overwriting old {conf}", fg="yellow")
            sudocmd("cp", nnginxfile, conffile)
            if nnginxfile != nginxfile:
                nnginxfile.unlink(missing_ok=True)
        else:
            sudocmd("cp", nginxfile, conffile)

        if sudocmd("nginx", "-t", check=False).returncode != 0:
            sudocmd("rm", conffile)
            if bak is not None:
                sudocmd("mv", bak, conffile)
            click.secho("nginx configuration faulty", fg="red", err=True)
            return None if bak is None else conf
        if bak is not None:
            bak.unlink(missing_ok=True)

        systemctlcmd("restart", "nginx")
    else:
        click.secho(f"nginx file {conf} unchanged", fg="green")
    return conf


def nginx_uninstall(nginxconf: str, *, save_copy: bool = False) -> None:
    from ..config import get_config

    config = get_config()
    nginxfile = Path(nginxconf)
    conf = nginxfile.name
    if "." not in conf:
        conf += ".conf"
    sudo = which("sudo")
    systemctl = which("systemctl")

    def sudocmd(*args: str, check: bool = True) -> subprocess.CompletedProcess[bytes]:
        return subprocess.run([sudo, *args], check=check)

    def cmd(*args: str, check: bool = True) -> subprocess.CompletedProcess[bytes]:
        return subprocess.run([*args], check=check)

    def systemctlcmd(*args: str, check: bool = True) -> int:
        return subprocess.run([sudo, systemctl, *args], check=check).returncode

    for d in config.nginx_dirs:
        fname = Path(d) / conf
        if fname.is_file():
            if save_copy:
                cp = Path.cwd() / f"{fname.name}.save"
                click.secho(f"saving copy of {fname} to {cp}", fg="yellow", err=True)
                cmd("cp", str(fname), str(cp))
            sudocmd("rm", str(fname))
            systemctlcmd("restart", "nginx.service")
            return

    click.secho(f"no nginx file {nginxfile}", fg="yellow", err=True)


